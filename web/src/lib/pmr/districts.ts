const norm = (s: unknown): string =>
  String(s ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, "");

/** District (DCE/DSE/DSO) d'une gare, « » si inconnue. */
export function districtForStation(station: unknown): District | "" {
  const k = norm(station);
  return (k && STATION_DISTRICT[k]) || "";
}
